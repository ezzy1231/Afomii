#!/usr/bin/env node
/**
 * Build the single-file Supabase schema snapshot from the numbered migrations.
 *
 * WHY THIS EXISTS
 * `packages/supabase/apply.sql` and `apply-all-migrations.sql` were both
 * hand-maintained copies that silently went stale (apply.sql excludes the
 * 0007 security hardening; apply-all-migrations.sql only covers 0001..0010).
 * Those are exactly the migrations you must NOT miss on a fresh project.
 * This script regenerates the combined file from the canonical sources, so the
 * snapshot can never drift.
 *
 * USAGE
 *   node scripts/build-supabase-apply.mjs           # write the combined file
 *   node scripts/build-supabase-apply.mjs --check   # verify no drift (CI)
 *
 * The combined file is for the Supabase SQL Editor (paste + run ONCE).
 * For scripted applies use scripts/apply-supabase-migrations.ps1, which feeds
 * the numbered files to psql one at a time so a failure names its migration.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS_DIR = join(ROOT, 'packages', 'supabase', 'migrations');
const OUTPUT = join(ROOT, 'packages', 'supabase', 'apply-all-migrations.sql');

/** Numeric-prefix ordering (0001 < 0002 < ... < 0014), not lexicographic. */
function listMigrations() {
  if (!existsSync(MIGRATIONS_DIR)) {
    console.error(`ERROR: migrations directory not found: ${MIGRATIONS_DIR}`);
    process.exit(1);
  }
  return readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort((a, b) => {
      const na = Number.parseInt(a.slice(0, 4), 10);
      const nb = Number.parseInt(b.slice(0, 4), 10);
      if (Number.isNaN(na) || Number.isNaN(nb)) return a.localeCompare(b);
      return na - nb;
    });
}

const files = listMigrations();
if (files.length === 0) {
  console.error('ERROR: no .sql migrations found.');
  process.exit(1);
}

const banner = `-- ============================================================================
-- UrbanExplore — ALL numbered migrations, concatenated in order (GENERATED FILE)
-- ============================================================================
-- DO NOT EDIT BY HAND. Generated by scripts/build-supabase-apply.mjs
-- Canonical sources: packages/supabase/migrations/ (apply in filename order)
-- Regenerate after adding a migration:  node scripts/build-supabase-apply.mjs
-- Verify no drift (use in CI):           node scripts/build-supabase-apply.mjs --check
--
-- HOW TO USE
--   Supabase SQL Editor: paste this whole file and run it ONCE against an EMPTY
--   project. Prefer scripts/apply-supabase-migrations.ps1, which applies each
--   numbered file separately and names the failing migration.
--
-- !! NOT IDEMPOTENT — run exactly once on a fresh project. !!
--   RLS policies are created with plain \`create policy\` (no preceding
--   \`drop policy if exists\`), and 0007 renames a column, so a second run will
--   error. That is fine for a new project; to re-apply, recreate the project or
--   apply only the migrations you still need.
--
-- !! pg_cron (migration 0006) !!
--   0006 schedules hold-expiry jobs with pg_cron. Enable it first:
--   Dashboard -> Database -> Extensions -> pg_cron, or the apply will stop at 0006.
-- ============================================================================

`;

const parts = [];
const manifest = [];

for (const file of files) {
  const body = readFileSync(join(MIGRATIONS_DIR, file), 'utf8').replace(/\s+$/, '');
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  const lineCount = body.split('\n').length;
  manifest.push({ file, lineCount, hash });
  parts.push(
    [
      '',
      `-- ================= ${file} =================`,
      `-- (${lineCount} lines, sha256:${hash})`,
      '',
      body,
      '',
    ].join('\n')
  );
}

const generated =
  banner +
  '-- Migration manifest\n' +
  manifest.map((m) => `--   ${m.file.padEnd(32)} ${String(m.lineCount).padStart(4)} lines  sha256:${m.hash}`).join('\n') +
  '\n' +
  parts.join('\n');

// ---- --check mode: fail if the committed snapshot has drifted from sources ----
if (process.argv.includes('--check')) {
  if (!existsSync(OUTPUT)) {
    console.error(`FAIL: ${OUTPUT} does not exist. Run without --check to generate it.`);
    process.exit(1);
  }
  const current = readFileSync(OUTPUT, 'utf8');
  if (current !== generated) {
    console.error('FAIL: apply-all-migrations.sql is out of date with packages/supabase/migrations/.');
    console.error('      Run: node scripts/build-supabase-apply.mjs');
    process.exit(1);
  }
  console.log(`OK: apply-all-migrations.sql matches ${files.length} migration(s).`);
  process.exit(0);
}

writeFileSync(OUTPUT, generated, 'utf8');

console.log(`Wrote ${OUTPUT}`);
console.log(`  ${files.length} migrations, ${generated.split('\n').length} lines total\n`);
for (const m of manifest) {
  console.log(`  ${m.file.padEnd(32)} ${String(m.lineCount).padStart(4)} lines  sha256:${m.hash}`);
}
